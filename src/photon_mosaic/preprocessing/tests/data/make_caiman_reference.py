"""Make ``caiman_reference.npz``: CaImAn 1.13.2's motion correction of a small synthetic movie.

``test_normcorre_registration.py`` checks the normcorre backend against it. The movie is
stored with the results rather than regenerated by the test, since numpy does not promise
the same random numbers across versions. CaImAn is on conda-forge only::

    conda create -p ./caiman-env -c conda-forge python=3.11 caiman=1.13.2
    ./caiman-env/bin/python make_caiman_reference.py
"""

import tempfile
from pathlib import Path

import caiman
import cv2
import numpy as np
import scipy.ndimage as ndi
import tifffile
from caiman.motion_correction import MotionCorrect

T, SIZE, MARGIN = 40, 64, 8
# photon-mosaic's num_frames_split=20; MotionCorrect takes the number of splits instead
SPLITS = max(T // 20, 1)
COMMON = dict(
    max_shifts=(6, 6),
    niter_rig=1,
    splits_rig=SPLITS,
    splits_els=SPLITS,
    strides=(24, 24),
    overlaps=(16, 16),
    max_deviation_rigid=3,
    upsample_factor_grid=4,
    border_nan="copy",
)
CONFIGS = {
    "rigid": dict(pw_rigid=False),
    "nonrigid_remap": dict(pw_rigid=True),
    "nonrigid_fft": dict(pw_rigid=True, shifts_opencv=False),
}


def make_movie(seed: int = 0) -> np.ndarray:
    """A texture moved by a rigid shift plus a smooth non-rigid field per frame, with noise, as int16."""
    rng = np.random.default_rng(seed)
    texture = ndi.gaussian_filter(rng.random((SIZE + 2 * MARGIN,) * 2), 2)
    texture = (texture - texture.min()) / np.ptp(texture)
    yy, xx = np.mgrid[:SIZE, :SIZE].astype(float)
    frames = []
    for rigid, (a, b) in zip(rng.uniform(-3, 3, (T, 2)), rng.uniform(-1, 1, (T, 2))):
        dy = rigid[0] + a * np.sin(2 * np.pi * xx / SIZE)
        dx = rigid[1] + b * np.sin(2 * np.pi * yy / SIZE)
        frame = ndi.map_coordinates(texture, [yy + MARGIN + dy, xx + MARGIN + dx], order=3)
        # about 5% negative pixels, as in real recordings, exercise CaImAn's offsets
        frames.append(1000 * frame - 400 + rng.normal(0, 10, frame.shape))
    return np.round(frames).astype(np.int16)


def main() -> None:
    movie = make_movie()
    out = {
        "movie": movie,
        "versions": np.array([caiman.__version__, cv2.__version__, np.__version__]),
    }
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "movie.tif"
        tifffile.imwrite(path, movie)
        for name, config in CONFIGS.items():
            mc = MotionCorrect([str(path)], dview=None, **COMMON, **config)
            mc.motion_correct(save_movie=False)
            out[f"{name}_shifts_rig"] = np.array(mc.shifts_rig)
            if config["pw_rigid"]:
                out[f"{name}_x_shifts_els"] = np.array(mc.x_shifts_els)
                out[f"{name}_y_shifts_els"] = np.array(mc.y_shifts_els)
                out[f"{name}_template"] = mc.total_template_els
            else:
                out[f"{name}_template"] = mc.total_template_rig
    np.savez_compressed(Path(__file__).with_name("caiman_reference.npz"), **out)


if __name__ == "__main__":
    main()
